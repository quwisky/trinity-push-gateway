import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, mkdtemp, readFile, readdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const workspaceRoot = fileURLToPath(new URL('../../../', import.meta.url));
const generatedRoot = path.join(
  workspaceRoot,
  'apps/push-gateway-ui/src/app/api/generated',
);
const expectedFiles = [
  'admin-api.schemas.ts',
  'configuration/configuration.service.ts',
  'metrics/metrics.service.ts',
  'operations/operations.service.ts',
  'overview/overview.service.ts',
  'security/security.service.ts',
  'session/session.service.ts',
];
const expectedServices = new Map([
  ['configuration/configuration.service.ts', 'ConfigurationService'],
  ['metrics/metrics.service.ts', 'MetricsService'],
  ['operations/operations.service.ts', 'OperationsService'],
  ['overview/overview.service.ts', 'OverviewService'],
  ['security/security.service.ts', 'SecurityService'],
  ['session/session.service.ts', 'SessionService'],
]);
const generatedHeader =
  '/**\n' +
  ' * Generated by Orval from apps/push-gateway/openapi/admin-v1.yaml.\n' +
  ' * Do not edit manually. Run pnpm nx run push-gateway-ui:generate-api.\n' +
  ' */\n';

function runGenerator(outputDirectory) {
  const result = spawnSync(
    'pnpm',
    [
      'exec',
      'orval',
      '--config',
      'apps/push-gateway-ui/orval.config.ts',
      '--project',
      'adminApi',
      '--fail-on-warnings',
    ],
    {
      cwd: workspaceRoot,
      encoding: 'utf8',
      env: {
        ...process.env,
        TRINITY_ORVAL_OUTPUT_TARGET: path.join(outputDirectory, 'admin-api.ts'),
      },
      maxBuffer: 10 * 1024 * 1024,
    },
  );
  if (result.error !== undefined) {
    throw result.error;
  }
  if (result.status !== 0) {
    const output = `${result.stdout ?? ''}${result.stderr ?? ''}`.trim();
    throw new Error(`Orval generation failed:\n${output}`);
  }
}

async function manifest(directory) {
  const files = [];

  async function visit(current, relative) {
    const entries = await readdir(current, { withFileTypes: true });
    entries.sort((left, right) => left.name.localeCompare(right.name));

    for (const entry of entries) {
      const entryPath = path.join(current, entry.name);
      const relativePath = path.join(relative, entry.name);
      if (entry.isDirectory()) {
        await visit(entryPath, relativePath);
      } else if (entry.isFile()) {
        const contents = await readFile(entryPath);
        files.push({
          hash: createHash('sha256').update(contents).digest('hex'),
          path: relativePath.split(path.sep).join('/'),
        });
      } else {
        throw new Error(`Unsupported generated API artifact: ${relativePath}`);
      }
    }
  }

  await visit(directory, '');
  return files;
}

async function checkOwnedOutput(directory, generatedManifest) {
  const actualFiles = generatedManifest.map(({ path: filePath }) => filePath);
  if (JSON.stringify(actualFiles) !== JSON.stringify(expectedFiles)) {
    throw new Error(
      `Generated API artifacts changed: ${actualFiles.join(', ') || 'none'}.`,
    );
  }

  for (const filePath of actualFiles) {
    const source = await readFile(path.join(directory, filePath), 'utf8');
    if (!source.startsWith(generatedHeader)) {
      throw new Error(`${filePath} is missing the generated-code header.`);
    }

    const serviceName = expectedServices.get(filePath);
    if (serviceName === undefined) {
      continue;
    }
    if (!source.includes(`export class ${serviceName}`)) {
      throw new Error(`${filePath} must export ${serviceName}.`);
    }

    const requestRoutes = [
      ...source.matchAll(/this\.http\.\w+<[^>]+>\(\s*`([^`]+)`/gu),
    ].map((match) => match[1]);
    if (requestRoutes.length === 0) {
      throw new Error(`${filePath} contains no generated HTTP requests.`);
    }
    const invalidRoute = requestRoutes.find(
      (route) => !route.startsWith('/admin/api/v1/'),
    );
    if (invalidRoute !== undefined) {
      throw new Error(
        `${filePath} contains an invalid API route: ${invalidRoute}`,
      );
    }
  }
}

const expectedManifest = await manifest(generatedRoot);
await checkOwnedOutput(generatedRoot, expectedManifest);

const temporaryParent = path.join(workspaceRoot, '.nx/workspace-data');
await mkdir(temporaryParent, { recursive: true });
const temporaryRoot = await mkdtemp(
  path.join(temporaryParent, 'trinity-orval-check-'),
);

try {
  const firstOutput = path.join(temporaryRoot, 'first');
  const secondOutput = path.join(temporaryRoot, 'second');
  runGenerator(firstOutput);
  runGenerator(secondOutput);

  const firstManifest = await manifest(firstOutput);
  const secondManifest = await manifest(secondOutput);
  await checkOwnedOutput(firstOutput, firstManifest);
  await checkOwnedOutput(secondOutput, secondManifest);

  if (JSON.stringify(firstManifest) !== JSON.stringify(secondManifest)) {
    throw new Error('Orval generation is not deterministic across clean runs.');
  }
  if (JSON.stringify(firstManifest) !== JSON.stringify(expectedManifest)) {
    throw new Error(
      'Generated Admin API client has drifted; run the generate-api target.',
    );
  }
} finally {
  await rm(temporaryRoot, { force: true, recursive: true });
}

console.info(
  `Generated Admin API: ${expectedManifest.length} reviewed artifacts, deterministic and unchanged.`,
);
